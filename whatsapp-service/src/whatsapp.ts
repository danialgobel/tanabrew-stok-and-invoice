import pkg from "whatsapp-web.js";
const { Client, LocalAuth, MessageMedia } = pkg;
import pino from "pino";
import QRCode from "qrcode";
import fs from "node:fs";
import path from "node:path";

export interface WhatsAppGroupInfo {
  id: string;
  name: string;
  participantCount?: number;
}

export interface WhatsAppStatus {
  connected: boolean;
  connecting: boolean;
  user: {
    id: string;
    name?: string;
  } | null;
  qrCode: string | null;
  pairingCode: string | null;
  lastError: string | null;
}

const SESSION_DIR = path.resolve(process.cwd(), "wa_session");
const logger = pino({ level: process.env.LOG_LEVEL || "info" });

let client: InstanceType<typeof Client> | null = null;
let currentQr: string | null = null;
let currentQrDataUrl: string | null = null;
let currentPairingCode: string | null = null;
let isConnected = false;
let isConnecting = false;
let lastErrorMessage: string | null = null;
let initPromise: Promise<void> | null = null;

const getExecutableChromePath = (): string | undefined => {
  const candidates = [
    "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe",
    "C:\\Program Files (x86)\\Google\\Chrome\\Application\\chrome.exe",
    "/usr/bin/google-chrome",
    "/usr/bin/chromium-browser",
    "/usr/bin/chromium",
  ];
  for (const c of candidates) {
    if (fs.existsSync(c)) {
      return c;
    }
  }
  return undefined;
};

export async function initWhatsApp(forceNewSession = false, headless = true): Promise<void> {
  if (initPromise && !forceNewSession) {
    return initPromise;
  }

  if (client && !forceNewSession) {
    logger.info("WhatsApp client already initialized.");
    return;
  }

  if (forceNewSession) {
    if (client) {
      try {
        await client.destroy();
      } catch {}
      client = null;
    }
    if (fs.existsSync(SESSION_DIR)) {
      try {
        fs.rmSync(SESSION_DIR, { recursive: true, force: true });
        logger.info("Cleared previous session directory.");
      } catch (err) {
        logger.error({ err }, "Failed to clear session directory");
      }
    }
  }

  if (!fs.existsSync(SESSION_DIR)) {
    fs.mkdirSync(SESSION_DIR, { recursive: true });
  }

  isConnecting = true;
  isConnected = false;
  lastErrorMessage = null;

  initPromise = (async () => {
    try {
      const executablePath = getExecutableChromePath();
      logger.info({ executablePath, headless }, "Initializing WhatsApp Web client with Google Chrome...");

      client = new Client({
        authStrategy: new LocalAuth({ dataPath: SESSION_DIR }),
        puppeteer: {
          headless,
          executablePath,
          args: [
            "--no-sandbox",
            "--disable-setuid-sandbox",
            "--disable-dev-shm-usage",
            "--disable-accelerated-2d-canvas",
            "--no-first-run",
            "--no-zygote",
            "--disable-gpu",
            "--disable-extensions",
            "--disable-background-networking",
            "--disable-default-apps",
            "--disable-sync",
            "--mute-audio",
            "--js-flags=--max-old-space-size=256",
          ],
        },
      });

      client.on("qr", async (qr: string) => {
        currentQr = qr;
        isConnecting = true;
        isConnected = false;
        try {
          currentQrDataUrl = await QRCode.toDataURL(qr, { margin: 2, scale: 7 });
          logger.info("New QR Code generated by WhatsApp Web.");
        } catch (qrErr) {
          logger.error({ qrErr }, "Failed to generate QR Data URL");
        }
      });

      client.on("ready", () => {
        isConnected = true;
        isConnecting = false;
        currentQr = null;
        currentQrDataUrl = null;
        currentPairingCode = null;
        lastErrorMessage = null;
        logger.info({ user: client?.info?.wid?._serialized }, "WhatsApp connection READY! (Chrome Session Active)");
      });

      client.on("authenticated", () => {
        isConnecting = false;
        logger.info("WhatsApp client successfully AUTHENTICATED.");
      });

      client.on("auth_failure", (msg: string) => {
        isConnecting = false;
        isConnected = false;
        lastErrorMessage = `Auth failure: ${msg}`;
        logger.error({ msg }, "WhatsApp authentication failed");
      });

      client.on("disconnected", (reason: string) => {
        isConnected = false;
        isConnecting = false;
        lastErrorMessage = `Disconnected: ${reason}`;
        logger.warn({ reason }, "WhatsApp connection disconnected.");
      });

      await client.initialize();
    } catch (error: any) {
      isConnecting = false;
      isConnected = false;
      lastErrorMessage = error?.message || "Failed to initialize WhatsApp Web client";
      logger.error({ error }, "Error during initWhatsApp");
    } finally {
      initPromise = null;
    }
  })();

  return initPromise;
}

export function getWhatsAppStatus(): WhatsAppStatus {
  const userWid = client?.info?.wid;
  const userPhone = userWid?.user || "";
  const userName = client?.info?.pushname || undefined;

  return {
    connected: isConnected,
    connecting: isConnecting,
    user: isConnected && userPhone ? {
      id: userPhone,
      name: userName,
    } : null,
    qrCode: currentQrDataUrl,
    pairingCode: currentPairingCode,
    lastError: lastErrorMessage,
  };
}

export async function requestPairingCode(phoneNumber: string): Promise<string> {
  if (isConnected) {
    throw new Error("WhatsApp sudah terhubung.");
  }

  let cleanedNumber = phoneNumber.replace(/\D/g, "");
  if (cleanedNumber.startsWith("0")) {
    cleanedNumber = "62" + cleanedNumber.slice(1);
  } else if (cleanedNumber.startsWith("8")) {
    cleanedNumber = "62" + cleanedNumber;
  }

  if (cleanedNumber.length < 10) {
    throw new Error("Nomor telepon tidak valid. Masukkan nomor lengkap (contoh: 0857... atau 62857...).");
  }

  if (!client) {
    await initWhatsApp();
  }

  if (!client) {
    throw new Error("Gagal menginisialisasi WhatsApp client.");
  }

  try {
    const code = await client.requestPairingCode(cleanedNumber);
    currentPairingCode = code;
    logger.info(`Pairing code requested for ${cleanedNumber}: ${code}`);
    return code;
  } catch (error: any) {
    logger.error({ error }, "Failed to request pairing code");
    throw new Error(error?.message || "Gagal meminta pairing code WhatsApp.");
  }
}

export async function getWhatsAppGroups(): Promise<WhatsAppGroupInfo[]> {
  if (!client || !isConnected) {
    throw new Error("WhatsApp belum terhubung.");
  }

  // Method 1: Direct Puppeteer evaluation to bypass modern WhatsApp Web serialize obfuscation ('r' bug)
  try {
    const page = (client as any).pupPage;
    if (page) {
      const extracted = await page.evaluate(() => {
        try {
          const win = globalThis as any;
          const collections = win.require?.("WAWebCollections");
          const chats = collections?.Chat?.getModelsArray?.() || [];
          const groups: Array<{ id: string; name: string; participantCount?: number }> = [];

          for (const c of chats) {
            const isGroupChat = Boolean(c.isGroup) || (c.id?._serialized && String(c.id._serialized).endsWith("@g.us"));
            if (isGroupChat) {
              const id = c.id?._serialized || String(c.id);
              const name = c.formattedTitle || c.name || c.contact?.name || "Grup Tanabrew";
              const participantCount = c.groupMetadata?.participants?.length || 0;
              groups.push({ id, name, participantCount });
            }
          }
          return groups;
        } catch {
          return null;
        }
      });

      if (Array.isArray(extracted) && extracted.length > 0) {
        logger.info(`Successfully retrieved ${extracted.length} WhatsApp groups via direct collection.`);
        return extracted.sort((a, b) => a.name.localeCompare(b.name));
      }
    }
  } catch (evalErr: any) {
    logger.warn({ evalErr: evalErr?.message }, "Direct page evaluation for groups failed, attempting fallback...");
  }

  // Method 2: Standard whatsapp-web.js getChats() fallback
  try {
    const chats = await client.getChats();
    const groupsList: WhatsAppGroupInfo[] = chats
      .filter((c: any) => c.isGroup)
      .map((g: any) => ({
        id: g.id?._serialized || String(g.id),
        name: g.name || "Tanpa Nama",
        participantCount: g.groupMetadata?.participants?.length || 0,
      }))
      .sort((a, b) => a.name.localeCompare(b.name));

    return groupsList;
  } catch (error: any) {
    logger.warn({ error: error?.message }, "Standard getChats failed to fetch WhatsApp groups");
  }

  return [];
}

export async function sendInvoicePdf(params: {
  groupId: string;
  pdfBuffer: Buffer;
  fileName: string;
  caption: string;
}): Promise<{ messageId: string }> {
  if (!client || !isConnected) {
    throw new Error("WhatsApp tidak terhubung. Pastikan server WhatsApp aktif.");
  }

  const { groupId, pdfBuffer, fileName, caption } = params;

  if (!groupId) {
    throw new Error(`Group ID WhatsApp tidak valid: ${groupId}`);
  }

  if (!pdfBuffer || pdfBuffer.length === 0) {
    throw new Error("File PDF kosong.");
  }

  try {
    logger.info({ groupId, fileName, sizeBytes: pdfBuffer.length }, "Sending invoice PDF to WhatsApp group via Chrome...");

    const cleanFileName = fileName.endsWith(".pdf") ? fileName : `${fileName}.pdf`;
    const media = new MessageMedia(
      "application/pdf",
      pdfBuffer.toString("base64"),
      cleanFileName
    );

    const sent = await client.sendMessage(groupId, media, {
      caption: caption || `Invoice ${cleanFileName}`,
    });

    const messageId = sent?.id?.id || "msg-" + Date.now();
    logger.info({ messageId, groupId }, "Invoice PDF successfully delivered to WhatsApp group!");
    return { messageId };
  } catch (error: any) {
    logger.error({ error, groupId, fileName }, "Failed to send invoice PDF to WhatsApp group");
    throw new Error(error?.message || "Gagal mengirim dokumen PDF ke grup WhatsApp.");
  }
}

export async function disconnectWhatsApp(): Promise<void> {
  if (client) {
    try {
      await client.logout();
    } catch {}
    try {
      await client.destroy();
    } catch {}
    client = null;
  }

  isConnected = false;
  isConnecting = false;
  currentQr = null;
  currentQrDataUrl = null;
  currentPairingCode = null;

  if (fs.existsSync(SESSION_DIR)) {
    try {
      fs.rmSync(SESSION_DIR, { recursive: true, force: true });
    } catch {}
  }

  logger.info("WhatsApp session disconnected and session directory cleared.");
  void initWhatsApp(true);
}
